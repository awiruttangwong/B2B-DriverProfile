-- ธงบอกว่ารถคันนี้เป็น "รถบริษัท" — ผูกกับทะเบียน (vehicles) ไม่ใช่คนขับ เพราะคนขับ
-- ลาออก/เลิกวิ่งได้ แต่ตัวรถยังเป็นรถบริษัทเหมือนเดิม ไม่ว่าใครจะมาขับ
--
-- 4 คันแรกที่ผู้ใช้ให้มา (3ฌท2757, 3ฌท2758, 3ฌย7928, 3ฌย7931) ถามพนักงานแล้วว่าทะเบียนจริง
-- สะกดด้วย "ฒ" ไม่ใช่ "ฌ" ตรงกับที่ระบบเราบันทึกไว้อยู่แล้วเป๊ะ (3ฒท2757 ฯลฯ) จึงแค่ตั้งธง
-- ไม่ต้องแก้ทะเบียนอะไร
--
-- 8 คันตรวจกับ ALLMANUAL_cleaned.xlsx (ไฟล์ต้นฉบับจริง) ตรงเป๊ะทุกคัน มีแถวอยู่แล้วในระบบ
-- ทั้งหมด ไม่ต้องสร้างใหม่สักคัน:
--   • 3ฒท2757, 3ฒท2758, 3ฒย7928, 3ฒย7931, 70-7616, 71-7486, 73-2203/73-2204 — ตรงตัว
--   • 707613 ที่ผู้ใช้ให้มา แท้จริงคือ "71-7613" (เลขท้ายตรง แต่นำหน้าเป็น 71 ไม่ใช่ 70) —
--     ก่อนหน้านี้เดาผิดว่าไม่มีคันนี้ในระบบเลยจะสร้างแถวใหม่ชื่อ "70-7613" ขึ้นมา (ผิด — เดา
--     เลขนำหน้าไปเองแบบไม่ได้ตรวจ) พอไล่ทะเบียนดิบทุกแถวในไฟล์ต้นฉบับจริงเจอ "71-7613" มีประวัติ
--     งานจริงจำนวนมาก (มี.ค.–ส.ค. 2026) จึงแก้เป็นตั้งธงที่แถวเดิมแทน ไม่ต้องสร้างแถวปลอมอีก
--
-- คนขับที่ขับแต่ละทะเบียนในประวัติงานจริงมีหลายคนสลับกัน ไม่ตรงกับชื่อเดียวที่ผู้ใช้ให้มาเป๊ะ
-- ทุกคัน (เช่น 3ฒท2758 มีคนขับอย่างน้อย 2 คนสลับกันในไฟล์) ซึ่งเป็นเรื่องปกติของรถบริษัท —
-- ตอกย้ำเหตุผลที่ตั้งธงที่ทะเบียนไม่ใช่ที่คนขับ
--
-- 3 ใน 8 ทะเบียนถูกบันทึกไม่เป๊ะเหมือนกันทุกครั้ง (เว้นวรรคเพี้ยน/ขาดตัวอักษร/มีคำต่อท้าย)
-- กลายเป็นรถ "คันเดียวกัน" ที่มีหลายแถวแยกกันอยู่ในตาราง vehicles ถ้าตั้งธงแค่สะกดหลัก
-- ป้ายรถบริษัทจะขึ้นแค่บางเที่ยว ไม่ใช่ทุกเที่ยวของรถคันนั้น จึงตั้งธงครบทุกตัวสะกดที่เจอจริง
-- ในไฟล์ต้นฉบับด้วย:
--   • 3ฒท2757  ยังมี "ฒท2757" (ขาดเลข 3 นำหน้า) — 61 เที่ยว
--   • 3ฒย7928  ยังมี "3ฒย 7928" (เว้นวรรค) และ "3ฒย7928กทม" (มีคำต่อท้าย) — 6 + 55 เที่ยว
--   • 3ฒย7931  ยังมี "3 ฒย7931" และ "3ฒย 7931" (เว้นวรรคคนละตำแหน่ง) — 8 + 134 เที่ยว
--     (ตัวสะกดหลักเองมีแค่ 29 เที่ยว — ตัวแปรที่เว้นวรรคกลับมีเที่ยวมากกว่าซะอีก)
-- อีก 5 คัน (3ฒท2758, 70-7616, 71-7486, 71-7613, 73-2203/73-2204) สะกดเดียวตลอดทุกเที่ยว
-- ไม่มีตัวแปร
--
-- รันซ้ำได้: เพิ่มคอลัมน์แบบ if not exists ตั้งธงด้วย update ไม่มี insert เลย
-- =============================================================================

alter table vehicles add column if not exists is_company boolean not null default false;

update vehicles
set is_company = true
where plate in (
  '3ฒท2757', 'ฒท2757',
  '3ฒท2758',
  '3ฒย7928', '3ฒย 7928', '3ฒย7928กทม',
  '3ฒย7931', '3 ฒย7931', '3ฒย 7931',
  '70-7616', '71-7486', '71-7613', '73-2203/73-2204'
);

-- ต่อ is_company ท้าย driver_job_history เหมือนที่ 0005 ต่อ seq_no ไว้ก่อนหน้า — create or
-- replace แทน drop + create เพื่อไม่ให้ grant/policy ของมุมมองหาย เพิ่มคอลัมน์ต่อท้ายได้เลย
-- ตราบใดที่คอลัมน์เดิมยังเรียงเหมือนเดิมทุกตัว (คัดลอกมาจาก 0005 แล้วต่อบรรทัดเดียว)
create or replace view driver_job_history
with (security_invoker = on) as
select
  a.id            as assignment_id,
  a.driver_id,
  j.id            as job_id,
  j.job_date,
  c.code          as customer_code,
  vt.code         as vehicle_type_code,
  v.plate,
  j.route_raw,
  j.origin,
  j.destination,
  j.revenue,
  j.cost,
  j.margin,
  j.note,
  a.outcome,
  a.on_time,
  r.id            as rating_id,
  r.overall_score,
  r.reason        as rating_reason,
  r.tags          as rating_tags,
  j.seq_no,
  v.is_company
from job_assignments a
join jobs j                on j.id = a.job_id
left join customers c      on c.id = j.customer_id
left join vehicle_types vt on vt.id = j.vehicle_type_id
left join vehicles v       on v.id = j.vehicle_id
left join driver_ratings r on r.assignment_id = a.id and r.voided_at is null;
