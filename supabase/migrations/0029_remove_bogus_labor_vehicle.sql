-- =============================================================================
-- 0029_remove_bogus_labor_vehicle.sql
--
-- ต่อจาก 0028: แถวต้นทางที่ทำให้เกิดประเภทรถ "แรงงาน" ยังเขียนคำเดียวกัน ("แรงงานลงสินค้า")
-- ไว้ในคอลัมน์ทะเบียนด้วย ระบบเลยสร้าง "รถ" ปลอมขึ้นมาหนึ่งคันจากข้อความนี้ — ไม่ใช่ทะเบียนจริง
-- ลบทิ้งตามที่แจ้ง (0028 ล้างแค่ vehicle_type_id ของรถคันนี้ไว้ ไม่ได้ลบตัวรถ)
--
-- ต้องล้าง jobs.vehicle_id ของเที่ยวที่ชี้มาที่นี่ก่อน (มี 1 เที่ยวในข้อมูลอ้างอิงที่ตรวจไว้)
-- ไม่งั้นจะชนข้อจำกัดคีย์นอกเหมือนตอนลบ vehicle_types ใน 0028 — เที่ยวงานเองไม่ถูกลบ แค่ไม่มี
-- รถอ้างอิงอีกต่อไป (plate ที่เก็บเป็นข้อความดิบในแถว jobs เองยังอยู่ตามเดิม เป็นแค่บันทึกว่า
-- ตอนนั้นกรอกอะไรมา ไม่ใช่คีย์นอก จึงไม่กระทบอะไร)
--
-- รันซ้ำได้: ถ้าไม่มีรถทะเบียนนี้อยู่แล้วไม่ทำอะไร
-- =============================================================================

do $$
declare
  v_id    uuid;
  v_jobs  int;
begin
  select id into v_id from vehicles where plate = 'แรงงานลงสินค้า';

  if v_id is null then
    raise notice 'ไม่พบรถทะเบียน "แรงงานลงสินค้า" (อาจลบไปแล้ว) — ไม่ต้องทำอะไร';
    return;
  end if;

  update jobs set vehicle_id = null where vehicle_id = v_id;
  get diagnostics v_jobs = row_count;

  delete from vehicles where id = v_id;

  raise notice 'ล้างรถออกจาก % เที่ยว และลบรถทะเบียน "แรงงานลงสินค้า" แล้ว', v_jobs;
end $$;
