-- -----------------------------------------------------------------------------
-- 1) แก้สูตรคะแนน — ตัด Bayesian shrinkage ออก
--
-- ของเดิม: adjusted = (m*C + Σ s·w) / (C + Σ w) โดย C = 5
-- ตั้ง C = 5 ไว้เพราะโมเดลเดิมคนหนึ่งจะสะสมรีวิวได้หลายสิบใบ (Σw ใหญ่) ค่าคงที่
-- จึงแค่กันคนที่ได้ 5.00 จากงานเดียวไม่ให้ชนะคนที่ได้ 4.6 จาก 40 งาน
--
-- แต่ในโมเดลใหม่ทุกคนมีใบประเมินคนละ "หนึ่งใบ" (Σw ≈ 1) ค่าคงที่ตัวเดิมจะกลืน
-- คะแนนจริงไปถึง 83% — คำนวณจริงเมื่อค่ากลางระบบ = 3.8:
--      ประเมิน 5.00 → แสดง (3.8*5 + 5.0)/(5+1) = 4.00
--      ประเมิน 2.00 → แสดง (3.8*5 + 2.0)/(5+1) = 3.50
-- ห่างกันจริง 3.00 คะแนน แต่บนหน้าจอเหลือ 0.50 ทุกคนจะกองอยู่แถว 3.5-4.0
-- และการจัดอันดับใน "หาคนสำหรับงาน" ก็แทบแยกคนเก่งกับคนแย่ไม่ออก
--
-- ตัด C ทิ้ง (C = 0) แล้ว adjusted = ค่าเฉลี่ยถ่วงน้ำหนักความสดล้วน ๆ
-- ถ้ามีใบเดียวก็เท่ากับคะแนนที่ผู้ประเมินให้ตรง ๆ ไม่มีการบวกค่ากลางที่ไม่มีใครให้
-- ตรงกับหลักของระบบนี้ที่ไม่แสดงตัวเลขที่ระบบคิดขึ้นเอง
--
-- ผลข้างเคียงที่ยอมรับ: เมื่อมีใบเดียว น้ำหนักความสดจะหักล้างตัวเอง (s·w)/w = s
-- ใบที่ประเมินไว้ 3 ปีก่อนจึงแสดงเต็มค่า — จึงต้องโชว์ "ประเมินล่าสุดเมื่อไร"
-- บนหน้าโปรไฟล์แทน ให้ความเก่าเห็นด้วยตาแทนการซ่อนไว้ในตัวเลข
-- -----------------------------------------------------------------------------
create or replace view driver_scorecard
with (security_invoker = on) as
with weighted as (
  select
    r.driver_id,
    r.overall_score as s,
    -- ครึ่งชีวิต 6 เดือน — ยังมีผลเมื่อคนหนึ่งถูกประเมินซ้ำหลายรอบ
    -- cast ให้ชัดเจน: extract(epoch ...) คืน double precision ถ้าปล่อยไว้
    -- ผลรวมจะกลายเป็น double precision แล้ว round(..., 2) จะพัง
    power(0.5::numeric,
          (extract(epoch from (now() - r.created_at))::numeric / (86400 * 182.5)::numeric)) as w
  from driver_ratings r
  where r.voided_at is null
)
select
  d.id                                                as driver_id,
  count(w.s)                                          as rating_count,
  round(avg(w.s)::numeric, 2)                         as raw_score,
  case
    when count(w.s) = 0 then null
    else round(sum(w.s * w.w) / sum(w.w), 2)
  end                                                 as adjusted_score,
  max(w.s)                                            as best_score,
  min(w.s)                                            as worst_score
from drivers d
left join weighted w on w.driver_id = d.id
group by d.id;

-- -----------------------------------------------------------------------------
-- 2) คิว "รอประเมิน" — เปลี่ยนหน่วยจากเที่ยวเป็นคน
--
-- is_priority: คนที่ควรประเมินก่อนจริง ๆ วัดจากข้อมูลจริงบน production
--   พขร. active ทั้งหมด                        1,290 คน
--   ในนั้นวิ่งแค่เที่ยวเดียวตลอดกาล              721 คน (56%)
--   เข้าเกณฑ์ >=10 เที่ยว หรือ วิ่งใน 90 วัน       336 คน
-- ถ้าไล่ให้ประเมินครบ 1,290 คนก็กลับไปเป็นปัญหาเดิมคือคิวที่ไม่มีวันหมด
-- ทั้งที่ครึ่งหนึ่งเป็นคนที่วิ่งครั้งเดียวแล้วไม่กลับมาอีกเลย จึงแยกธงไว้ให้หน้าเว็บ
-- ตั้งค่าเริ่มต้นโชว์เฉพาะกลุ่มที่มีผลต่องานจริง แต่ยังกดดูทั้งหมดได้ ไม่ได้ซ่อนใคร
-- -----------------------------------------------------------------------------
drop view if exists pending_ratings;

create view drivers_pending_review
with (security_invoker = on) as
select
  d.id,
  d.driver_code,
  d.full_name,
  d.phone,
  d.status,
  coalesce(s.total_jobs, 0)    as total_jobs,
  s.last_job_date,
  s.days_since_last_job,
  coalesce(sc.rating_count, 0) as rating_count,
  (coalesce(s.total_jobs, 0) >= 10
   or coalesce(s.days_since_last_job, 2147483647) <= 90) as is_priority
from drivers d
left join driver_stats s      on s.driver_id = d.id
left join driver_scorecard sc on sc.driver_id = d.id
where coalesce(sc.rating_count, 0) = 0
  and d.status in ('active', 'probation');

grant select on drivers_pending_review to authenticated;
