/**
 * แถวโครงร่างระหว่างโหลดตาราง — ใช้แทนสปินเนอร์ลอยเดี่ยว ๆ กลางช่องว่าง
 *
 * เดิมมีแค่หน้ารายชื่อ พขร. (Drivers.tsx) ที่ทำแบบนี้ ส่วนตารางอื่น (พักงาน,
 * แบล็คลิสต์, รอประเมิน, ประวัติงานในโปรไฟล์) ยังใช้ "สปินเนอร์เล็ก ๆ + กำลังโหลด…"
 * ลอยอยู่กลางกล่องว่างเปล่า ซึ่งดูไม่นิ่งเพราะพอโหลดเสร็จตารางจะ "กระโดด" จากช่องว่าง
 * เป็นแถวข้อมูลทันที ต่างจากโครงร่างที่บอกรูปร่าง/ตำแหน่งคอลัมน์ไว้ล่วงหน้า ตารางจึง
 * ดูเหมือนกำลังค่อย ๆ ปรากฏแทนที่จะสลับฉากกะทันหัน — ย้ายมาเป็นคอมโพเนนต์กลางตัวนี้
 * ให้ทุกตารางใช้ร่วมกัน แทนที่จะก๊อปโครงเดิมไปแก้ทีละหน้า
 */

interface Column {
  /** สัดส่วนความกว้างแท่งโครงร่างเทียบกับความกว้างคอลัมน์ */
  width?: string
  /** ต้องตรงกับการจัดตำแหน่งจริงของคอลัมน์นั้น ไม่งั้นแท่งโครงร่างจะไม่อยู่ตำแหน่ง
   *  เดียวกับข้อมูลจริงที่กำลังจะมา (ค่าเริ่มต้น 'left') */
  align?: 'left' | 'center'
}

interface Props {
  columns: Column[]
  rows?: number
}

export default function SkeletonRows({ columns, rows = 6 }: Props) {
  return (
    <>
      {Array.from({ length: rows }).map((_, i) => (
        // aria-hidden ต่อแถว ไม่ใช่ที่ Fragment ครอบ (Fragment วางแอตทริบิวต์ไม่ได้ ไม่มี
        // node จริงให้ติด) ไม่งั้นโปรแกรมอ่านหน้าจอจะประกาศ "แถวว่าง" ซ้ำ ๆ ตามจำนวน rows
        // ระหว่างที่ตารางกำลังโหลดอยู่ — ให้สอดคล้องกับ SkeletonListItems.tsx ที่ทำไว้แล้ว
        <tr key={i} aria-hidden="true">
          {columns.map((col, j) => (
            <td key={j}>
              <div
                className="sk"
                style={{
                  width: col.width ?? '50%',
                  marginLeft: col.align === 'center' ? 'auto' : undefined,
                  marginRight: col.align === 'center' ? 'auto' : undefined,
                }}
              />
            </td>
          ))}
        </tr>
      ))}
    </>
  )
}
